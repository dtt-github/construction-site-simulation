"""Download registered 3D assets and keep license records honest.

    python assets/fetch_assets.py            # download every "fetched" asset that is missing
    python assets/fetch_assets.py --check    # only validate the registry (CI-friendly)
    python assets/fetch_assets.py --notice   # also rewrite the third-party section of NOTICE

Rules enforced: every asset has a source, author and an allowed license; downloads are written only
inside assets/ (or the asset's declared repo path); files listed with a sha256 are verified.
"""

import argparse
import hashlib
import json
import pathlib
import sys
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parent.parent
REGISTRY = ROOT / "assets" / "registry.json"
NOTICE = ROOT / "NOTICE"
ALLOWED = {"CC0-1.0", "CC-BY-3.0", "CC-BY-4.0", "CC-BY-SA-3.0", "CC-BY-SA-4.0", "MIT", "BSD-2-Clause", "BSD-3-Clause", "Apache-2.0", "Public-Domain"}
REQUIRED = ("id", "name", "category", "status", "source_url", "license", "license_url", "author", "attribution")
NOTICE_MARK = "## Third-party assets (generated by assets/fetch_assets.py --notice)"


def load():
    return json.loads(REGISTRY.read_text())


def validate(reg):
    errors = []
    seen = set()
    for a in reg["assets"]:
        for key in REQUIRED:
            if not a.get(key):
                errors.append(f"{a.get('id', '?')}: missing {key}")
        if a.get("license") not in ALLOWED:
            errors.append(f"{a.get('id')}: license {a.get('license')!r} is not allowed (see assets/README.md)")
        if a.get("license", "").startswith("CC-BY-SA") and not a.get("share_alike"):
            errors.append(f"{a.get('id')}: share-alike license must set \"share_alike\": true")
        if a.get("status") == "fetched" and not a.get("downloads"):
            errors.append(f"{a.get('id')}: status 'fetched' needs a downloads list")
        if a["id"] in seen:
            errors.append(f"duplicate id {a['id']}")
        seen.add(a["id"])
    return errors


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def fetch(reg):
    for a in reg["assets"]:
        if a["status"] != "fetched":
            continue
        for d in a["downloads"]:
            dest = (ROOT / d["path"]).resolve()
            if ROOT not in dest.parents:
                raise SystemExit(f"{a['id']}: refusing to write outside the repo: {dest}")
            if not dest.exists():
                dest.parent.mkdir(parents=True, exist_ok=True)
                print(f"downloading {a['id']} -> {d['path']}")
                req = urllib.request.Request(d["url"], headers={"User-Agent": "construction-site-simulation/asset-fetch"})
                with urllib.request.urlopen(req, timeout=120) as r, open(dest, "wb") as out:
                    out.write(r.read())
            if d.get("sha256") and sha256(dest) != d["sha256"]:
                raise SystemExit(f"{a['id']}: checksum mismatch for {d['path']}")


def write_notice(reg):
    lines = [NOTICE_MARK, ""]
    for a in sorted(reg["assets"], key=lambda x: (x["category"], x["id"])):
        mod = f" Modifications: {a['modifications']}." if a.get("modifications") else ""
        lines.append(f"- {a['attribution']}. Source: {a['source_url']}. License: {a['license']} ({a['license_url']}).{mod}")
    text = NOTICE.read_text() if NOTICE.exists() else ""
    head = text.split(NOTICE_MARK)[0].rstrip() + "\n\n" if NOTICE_MARK in text else text.rstrip() + "\n\n"
    NOTICE.write_text(head + "\n".join(lines) + "\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--notice", action="store_true")
    args = ap.parse_args()
    reg = load()
    errors = validate(reg)
    if errors:
        print("\n".join(errors))
        sys.exit(1)
    counts = {}
    for a in reg["assets"]:
        counts[a["status"]] = counts.get(a["status"], 0) + 1
    print(f"registry ok: {len(reg['assets'])} assets {counts}")
    if args.notice:
        write_notice(reg)
        print("NOTICE updated")
    if not args.check:
        fetch(reg)


if __name__ == "__main__":
    main()
